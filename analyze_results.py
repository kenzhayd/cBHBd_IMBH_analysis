# Helper Functions
def calculate_sigmas(data):
    """Calculates mean, 1σ, and 3σ bounds."""
    if len(data) == 0:
        return np.nan, np.nan, np.nan, np.nan, np.nan, np.nan
    mean_val = np.mean(data)
    std_val = np.std(data)
    return mean_val, std_val, mean_val - std_val, mean_val + std_val, mean_val - 3*std_val, mean_val + 3*std_val

def get_config_name(config_dict):
    """Creates filename string from config parameters."""
    seed_str = "Rantala" if config_dict['rantala_imbh_seed'] else "Standard CBHBD"
    imf_str = "ExtIMF" if config_dict['extended_imf'] else "Standard CBHBD"
    pot_str = "Galpy" if config_dict['galpy_potential'] else "Standard CBHBD"

    return (f"M0_{config_dict['M0']:.0e}_rhoh0_{config_dict['rhoh0']:.2e}_"
            f"FeH_{config_dict['FeH']}_Mvir_{config_dict['M_vir']:.1e}_"
            f"{seed_str}_{imf_str}_{pot_str}")

def compute_retention_flags(mergers_list):
    """
    Computes retained if not Ejected type or v_kick >= v_esc
    """

    df = pd.DataFrame(mergers_list)
    
    # Ensure required columns exist
    is_ejected_type = df['merger_type'].astype(str).str.contains('Ejected', case=False, na=False)
    is_kicked_out = df['v_kick'] >= df['v_esc']
    df['retained'] = ~(is_ejected_type | is_kicked_out)
        
    return df.to_dict(orient='records')

   

# Plotting Functions

def plot_aggregated_merger_histograms(all_mergers, config_name, output_dir):
    """Aggregated Retained vs Ejected Merger Mass Histograms."""
        
    df = pd.DataFrame(all_mergers)
    retained = df[df['retained']]['m_rem']
    ejected = df[~df['retained']]['m_rem']

    plt.figure(figsize=(10, 6))
    if not retained.empty:
        plt.hist(retained, bins=60, color=COLOURS[3],  alpha=0.6, label=f'Retained (N={len(retained)})')
    if not ejected.empty:
        plt.hist(ejected, bins=60, color=COLOURS[5], alpha=0.6, label=f'Ejected (N={len(ejected)})')
        
    plt.xlabel('Merger Product Mass ($M_{\\odot}$)', fontsize=14)
    plt.ylabel('Number of Mergers', fontsize=14)
    plt.yscale("log")
    plt.legend(fontsize=12)
    plt.grid(axis='y', linestyle='--', alpha=0.7)
    plt.tight_layout()
    plt.savefig(output_dir / f"{config_name}_merger_histograms.png", dpi=300)
    plt.close()

def plot_aggregated_kick_vs_time(all_mergers, stats_list, config_name, output_dir):
    """
    Plots the aggregated GW recoil kick velocity as a function of time,
    with merger product mass represented by a colormap.
    Ejected mergers are plotted as triangles, retained as circles.
    Overplots the mean cluster and total escape velocities as a function of time.
    """

    df = pd.DataFrame(all_mergers)

    retained = df[df['retained']]
    ejected = df[~df['retained']]

    fig, ax = plt.subplots(figsize=(10, 6))

    valid_m_rem = df['m_rem'].dropna()
    vmin = valid_m_rem.min() if not valid_m_rem.empty else 0
    vmax = valid_m_rem.max() if not valid_m_rem.empty else 100
    norm = plt.Normalize(vmin=vmin, vmax=vmax)
    cmap = plt.cm.viridis

    # Sort by merger product mass so that higher-mass circles are plotted last.
    if not ejected.empty:
        ejected_sorted = ejected.sort_values('m_rem', ascending=True)
        ax.scatter(
            ejected_sorted['t_merge'] / 1e6,
            ejected_sorted['v_kick'],
            c=ejected_sorted['m_rem'],
            cmap=cmap,
            norm=norm,
            marker='^',
            label='Ejected',
            alpha=0.6,
            s=60,
            #edgecolors='black',
            linewidth=0.5,
            zorder=1
        )

    if not retained.empty:
        retained_sorted = retained.sort_values('m_rem', ascending=True)
        ax.scatter(
            retained_sorted['t_merge'] / 1e6,
            retained_sorted['v_kick'],
            c=retained_sorted['m_rem'],
            cmap=cmap,
            norm=norm,
            marker='o',
            label='Retained',
            alpha=0.6,
            s=60,
            #edgecolors='black',
            linewidth=0.5,
            zorder=2
        )

    sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm)
    sm.set_array([])
    cbar = fig.colorbar(sm, ax=ax)
    cbar.set_label('Merger Product Mass ($M_{\\odot}$)', fontsize=12)

    sample_stats = stats_list[0]
    t_myr = np.array(sample_stats['vesc_t_myr']) if 'vesc_t_myr' in sample_stats else None

    
    # Prepare common time grid for escape velocities 
    # (Runs may terminate at different times)
    valid_stats = [s for s in stats_list if 'vesc_t_myr' in s and s['vesc_t_myr'] is not None and len(s['vesc_t_myr']) > 0]
    if valid_stats:
        t_max_esc = max(np.array(s['vesc_t_myr'])[-1] for s in valid_stats)
        common_t_esc = np.linspace(0.0, t_max_esc, 500)
    else:
        common_t_esc = None

    # Plot Total Escape Velocity
    if common_t_esc is not None:
        vesc_interp = []
        for s in valid_stats:
            if 'vesc' in s and s['vesc'] is not None and len(s['vesc']) > 0:
                t_arr = np.array(s['vesc_t_myr'])
                v_arr = np.array(s['vesc'])
                # Interpolate onto the common time grid
                v_interp = np.interp(common_t_esc, t_arr, v_arr, right=v_arr[-1])
                vesc_interp.append(v_interp)
        
        if vesc_interp:
            mean_vesc = np.mean(vesc_interp, axis=0)
            v_esc_total_0 = mean_vesc[0]
            ax.plot(common_t_esc, mean_vesc, color=COLOURS[0], linestyle='-', linewidth=3,
                    label=f'Total $v_{{esc}}$ (Init: {v_esc_total_0:.1f} km/s)', zorder=3)

    # Plot Cluster Escape Velocity 
    if common_t_esc is not None:
        vesc_cl_interp = []
        for s in valid_stats:
            if 'vesc_cl' in s and s['vesc_cl'] is not None and len(s['vesc_cl']) > 0:
                t_arr = np.array(s['vesc_t_myr'])
                v_arr = np.array(s['vesc_cl'])
                # Interpolate onto the common time grid
                v_interp = np.interp(common_t_esc, t_arr, v_arr, right=v_arr[-1])
                vesc_cl_interp.append(v_interp)
        
        if vesc_cl_interp:
            mean_vesc_cl = np.mean(vesc_cl_interp, axis=0)
            v_esc_cl_0 = mean_vesc_cl[0]
            ax.plot(common_t_esc, mean_vesc_cl, color=COLOURS[0], linestyle='--', linewidth=3,
                    label=f'Cluster $v_{{esc}}$ (Init: {v_esc_cl_0:.1f} km/s)', zorder=4)

    ax.set_xlabel('Time (Myr)', fontsize=14)
    ax.set_ylabel('GW Kick Velocity (km/s)', fontsize=14)
    ax.legend(fontsize=10, loc='best')
    ax.grid(True, linestyle='--', alpha=0.4, which='both')
    
    max_time_myr = (df['t_merge'].max() / 1e6) 
    ax.set_xlim(0, max_time_myr)

    plt.tight_layout()
    plot_path = output_dir / f"{config_name}_kick_vs_time.png"
    plt.savefig(plot_path, dpi=300, bbox_inches='tight')
    plt.close()
    


def plot_aggregated_growth_trajectory(all_trajectories, config_name, output_dir, all_mergers):
    """Aggregated Growth trajectory with 1σ and 3σ shaded regions."""
    valid_trajs = [t for t in all_trajectories if len(t['t_merge']) > 0]
    print(f"Total runs passed: {len(all_trajectories)}. Runs with retained mergers: {len(valid_trajs)}")

    df = pd.DataFrame(all_mergers)
    
    # Guard against empty trajectory lists
    if not valid_trajs:
        print(f"  [Warning] No valid trajectories for {config_name}. Skipping aggregated growth plot.")
        return

    # Create a common time grid from 0 to the maximum merger time across all runs
    all_times = np.concatenate([np.array(t['t_merge']) / 1e6 for t in valid_trajs])
    t_min, t_max = 0.0, np.max(all_times)
    time_grid = np.linspace(t_min, t_max, 200)
    masses_at_grid = []

    # Interpolate each run's step-function growth onto the common time grid
    for t in valid_trajs:
        times_myr = np.array(t['t_merge']) / 1e6
        masses = np.array(t['max_merger_mass'])
        interp_masses = np.interp(time_grid, times_myr, masses, left=0.0, right=masses[-1])
        masses_at_grid.append(interp_masses)
    
    masses_at_grid = np.array(masses_at_grid)  # shape: (N_seeds, 200)
    N = masses_at_grid.shape[0]
    mean_mass = np.mean(masses_at_grid, axis=0)
    std_mass = np.std(masses_at_grid, axis=0)

    # Initialize the figure
    plt.figure(figsize=(10, 6))

    # 1. Plot individual cross-trajectories (faint lines)
    for i, traj_masses in enumerate(masses_at_grid):
        plt.plot(time_grid, traj_masses, color=COLOURS[3], alpha=0.5, linewidth=0.8,
                 label='Individual runs' if i == 0 else None, zorder=1)

    # 2. Plot the Mean trajectory (bold line)
    plt.plot(time_grid, mean_mass, label=f'Mean Growth (N={N})',
             color=COLOURS[5], linewidth=2.5, zorder=4)

    # # 3. Plot Uncertainties (1σ and 3σ shaded regions)
    # if N >= 2 and np.max(std_mass) > 0:
    #     plt.fill_between(time_grid, mean_mass - std_mass, mean_mass + std_mass,
    #                      color=COLOURS[5], alpha=0.3, label='1σ', zorder=3)
    #     plt.fill_between(time_grid, mean_mass - 3*std_mass, mean_mass + 3*std_mass,
    #                      color=COLOURS[5], alpha=0.1, label='3σ', zorder=2)
    # else:
    #     print(f"Contours omitted. Increase SEEDS.")

    # Formatting
    plt.xlabel('Time (Myr)', fontsize=14)
    plt.ylabel('Largest Retained Remnant Mass ($M_{\\odot}$)', fontsize=14)
    plt.legend(fontsize=12)
    plt.grid(True, linestyle='--', alpha=0.7)
    plt.tight_layout()
    max_time_myr = (df['t_merge'].max() / 1e6) 
    plt.xlim(0, max_time_myr)

    
    # Save and close
    plt.savefig(output_dir / f"{config_name}_growth_trajectory.png", dpi=300)
    plt.close()

def plot_best_growth_trajectory(all_trajectories, config_name, output_dir, all_mergers):
    """Growth trajectory of the single most massive IMBH."""
    df = pd.DataFrame(all_mergers)
    
    valid_trajs = [t for t in all_trajectories if len(t['t_merge']) > 0]
    if not valid_trajs: return

    best_traj = max(valid_trajs, key=lambda t: t['max_merger_mass'][-1])
    times_myr = np.array(best_traj['t_merge']) / 1e6
    masses = np.array(best_traj['max_merger_mass'])

    plt.figure(figsize=(10, 6))
    plt.plot(times_myr, masses, marker='o', linestyle='-', color=COLOURS[5], linewidth=2, markersize=4, label='Most Massive IMBH of All')
    plt.xlabel('Time (Myr)', fontsize=14)
    plt.ylabel('Largest Retained Remnant Mass ($M_{\\odot}$)', fontsize=14)
    plt.legend(fontsize=12)
    plt.grid(True, linestyle='--', alpha=0.7)
    plt.tight_layout()
    max_time_myr = times_myr[-1] 
    plt.xlim(0, max_time_myr)
    plt.savefig(output_dir / f"{config_name}_best_growth_trajectory.png", dpi=300)
    plt.close()


# Main Analysis Loop
def analyze_and_plot(output_dir):
    
    output_dir = Path(output_dir)
    
    # 1. Find all data files
    data_files = list(output_dir.glob("run_*/data.json"))

    if not data_files:
        data_files = list(output_dir.glob("*/run_*/data.json"))

    if not data_files:
        data_files = [
            p for p in output_dir.glob("**/data.json")
            if "summary" not in p.parts
        ]

    if not data_files:
        print(f"No data.json files found in {output_dir}")
        return

    first_file = Path(data_files[0]).resolve()

    candidate_prefix = first_file.parent.parent.name

    generic_names = {
        "output",
        "local_test_output",
        "outputs",
        ".",
        ""
    }

    if candidate_prefix.lower() not in generic_names:
        summary_prefix = candidate_prefix
    else:
        summary_prefix = "generic_name"
        print(f"Could not infer a meaningful summary prefix from {first_file}. Using '{summary_prefix}'.")

    summary_dir = output_dir / f"{summary_prefix}_summary"
    summary_dir.mkdir(parents=True, exist_ok=True)

    print(f"Found {len(data_files)} run files.")
    
    
    # 2. Load and group by configuration
    configs_found = {}
    for file in data_files:
        with open(file, 'r') as f:
            data = json.load(f)
            
        stats = data['stats']
        
        config_key = (
            stats['M0'], stats['rhoh0'], stats['FeH'], stats['rg'], stats['tend'],
            stats['rantala_imbh_seed'], stats['extended_imf'], stats['galpy_potential'], 
            stats['M_vir'], stats['c_halo']
        )
        
        if config_key not in configs_found:
            configs_found[config_key] = {
                'stats_list': [],
                'mergers_list': [],
                'trajectories_list': []
            }
            
        configs_found[config_key]['stats_list'].append(stats)
        
        # Process mergers 
        raw_mergers = data.get('mergers', [])
        configs_found[config_key]['mergers_list'].extend(compute_retention_flags(raw_mergers))
        
        raw_traj = data.get('trajectory', {})
        traj_data = {
            't_merge': raw_traj.get('t_merge', []),
            'max_merger_mass': raw_traj.get('max_merger_mass', [])
        }
        configs_found[config_key]['trajectories_list'].append(traj_data)
        
    print(f"Identified {len(configs_found)} unique configurations.\n")

    # 3. Process each configuration
    aggregate_results = []
    for config_key, run_data in configs_found.items():
        stats_list = run_data['stats_list']
        config_dict = {
            'M0': config_key[0], 'rhoh0': config_key[1], 'FeH': config_key[2], 
            'rg': config_key[3], 'tend': config_key[4], 'rantala_imbh_seed': config_key[5],
            'extended_imf': config_key[6], 'galpy_potential': config_key[7], 
            'M_vir': config_key[8], 'c_halo': config_key[9]
        }
        config_name = get_config_name(config_dict)
        print(f"Processing: {config_name} ({len(stats_list)} runs)")

        # Aggregate Statistics 
        final_masses = [s['mIMBH_final'] for s in stats_list if not np.isnan(s.get('mIMBH_final', np.nan))]
        v_esc0_list = [s['v_esc0'] for s in stats_list if not np.isnan(s.get('v_esc0', np.nan))]
        v_esc_final_list = [s['v_esc_final'] for s in stats_list if not np.isnan(s.get('v_esc_final', np.nan))]
        
        mean_mass, std_mass, l1, u1, l3, u3 = calculate_sigmas(final_masses)
        mean_v_esc0 = np.mean(v_esc0_list) if v_esc0_list else np.nan
        mean_v_esc_final = np.mean(v_esc_final_list) if v_esc_final_list else np.nan

        summary = {
            "configuration": config_dict,
            "total_runs": len(stats_list),
            "final_IMBH_mass_mean": float(mean_mass),
            "final_IMBH_mass_std": float(std_mass),
            "final_IMBH_mass_1sigma": [float(l1), float(u1)],
            "final_IMBH_mass_3sigma": [float(l3), float(u3)],
            "mean_initial_v_esc": float(mean_v_esc0),
            "mean_final_v_esc": float(mean_v_esc_final),
        }
        aggregate_results.append(summary)

        # Generate Plots 
        plot_aggregated_merger_histograms(run_data['mergers_list'], config_name, summary_dir)
        plot_aggregated_kick_vs_time(run_data['mergers_list'],run_data['stats_list'], config_name, summary_dir)
        plot_best_growth_trajectory(run_data['trajectories_list'], config_name, summary_dir, run_data['mergers_list'])        
        plot_aggregated_growth_trajectory(run_data['trajectories_list'], config_name, summary_dir, run_data['mergers_list'])
        
        print(f"----> Saved plots to {summary_dir} :)\n ")

    # 4. Save statistics to CSV and JSON
    pd.DataFrame(aggregate_results).to_csv(
        summary_dir / f"{summary_prefix}_aggregate_stats.csv",
        index=False
    )

    with open(summary_dir / f"{summary_prefix}_aggregate_stats.json", 'w') as f:
        json.dump(aggregate_results, f, indent=4)
        
    print("Analysis complete!")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--output_dir",
        "--output-dir",
        dest="output_dir",
        type=str,
        default="output",
        help="Directory containing the output files"
    )

    args = parser.parse_args()

    print("=== Analysis ===")
    print(f"Output directory being analyzed: {args.output_dir}")

    analyze_and_plot(Path(args.output_dir))